-- FGF app learning loop + review page: player feedback, knowledge gaps and the admin audit log.
-- Run once in Supabase -> SQL Editor. Safe to re-run (also upgrades an earlier version of this script).
--
-- Security design (decided before enabling RLS, as the project rules require):
--   * Row Level Security is ON for the three new tables in this script only. No existing table is changed.
--   * The public (anon / publishable) key may INSERT new rows and nothing else:
--     it cannot read, change or delete feedback, so the app's proxy can't leak it.
--   * The daily learning workflow reads and updates rows with the secret key
--     (service role bypasses RLS), so no read policy is needed.
--   * No IP address, account or profile data is stored.
--   * knowledge_gaps and admin_audit have RLS on and NO policies: only the secret key
--     (learning workflow, review page via the AI proxy) can use them.

create table if not exists public.app_feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind text not null check (kind in ('helpful', 'not_helpful', 'correction', 'unanswered')),
  question text not null check (char_length(question) between 2 and 500),
  answer_excerpt text check (answer_excerpt is null or char_length(answer_excerpt) <= 1500),
  correction text check (correction is null or char_length(correction) <= 1000),
  source_url text check (source_url is null or (char_length(source_url) <= 500 and source_url ~* '^https?://')),
  cited_facts jsonb not null default '[]'::jsonb check (jsonb_typeof(cited_facts) = 'array' and jsonb_array_length(cited_facts) <= 8),
  app_version text check (app_version is null or char_length(app_version) <= 40),
  status text not null default 'new' check (status in ('new', 'needs_review', 'processed', 'ignored')),
  processed_at timestamptz,
  result jsonb not null default '{}'::jsonb
);

create index if not exists idx_app_feedback_status on public.app_feedback (status, created_at);

alter table public.app_feedback enable row level security;

revoke all on public.app_feedback from anon, authenticated;
grant insert (kind, question, answer_excerpt, correction, source_url, cited_facts, app_version)
  on public.app_feedback to anon;

drop policy if exists app_feedback_insert_only on public.app_feedback;
create policy app_feedback_insert_only on public.app_feedback
  for insert to anon
  with check (status = 'new' and processed_at is null and result = '{}'::jsonb);

-- Upgrade from the first version of this script (adds the 'needs_review' state).
alter table public.app_feedback drop constraint if exists app_feedback_status_check;
alter table public.app_feedback add constraint app_feedback_status_check
  check (status in ('new', 'needs_review', 'processed', 'ignored'));

-- Questions players ask that the knowledge base can't answer well (filled by FGF Player Learning).
create table if not exists public.knowledge_gaps (
  gap_key text primary key check (char_length(gap_key) between 1 and 200),
  example text not null,
  count integer not null default 0,
  unanswered integer not null default 0,
  not_helpful integer not null default 0,
  first_seen date,
  last_seen date,
  status text not null default 'open' check (status in ('open', 'covered', 'answered', 'dismissed')),
  covered_on date,
  resolved_note text,
  updated_at timestamptz not null default now()
);
create index if not exists idx_knowledge_gaps_open on public.knowledge_gaps (status, count desc);
alter table public.knowledge_gaps enable row level security;
revoke all on public.knowledge_gaps from anon, authenticated;

-- Every review decision (who: the owner via the review page; what; when; why).
create table if not exists public.admin_audit (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  action text not null,
  target text,
  detail jsonb not null default '{}'::jsonb
);
alter table public.admin_audit enable row level security;
revoke all on public.admin_audit from anon, authenticated;
