-- FGF app learning loop: anonymous player feedback (ratings, corrections, unanswered questions).
-- Run once in Supabase -> SQL Editor. Safe to re-run.
--
-- Security design (decided before enabling RLS, as the project rules require):
--   * Row Level Security is ON for this new table only. No existing table is changed.
--   * The public (anon / publishable) key may INSERT new rows and nothing else:
--     it cannot read, change or delete feedback, so the app's proxy can't leak it.
--   * The daily learning workflow reads and updates rows with the secret key
--     (service role bypasses RLS), so no read policy is needed.
--   * No IP address, account or profile data is stored.

create table if not exists public.app_feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind text not null check (kind in ('helpful', 'not_helpful', 'correction', 'unanswered')),
  question text not null check (char_length(question) between 2 and 500),
  answer_excerpt text check (answer_excerpt is null or char_length(answer_excerpt) <= 1500),
  correction text check (correction is null or char_length(correction) <= 1000),
  source_url text check (source_url is null or (char_length(source_url) <= 500 and source_url ~* '^https?://')),
  cited_facts jsonb not null default '[]'::jsonb check (jsonb_typeof(cited_facts) = 'array' and jsonb_array_length(cited_facts) <= 8),
  app_version text check (app_version is null or char_length(app_version) <= 40),
  status text not null default 'new' check (status in ('new', 'processed', 'ignored')),
  processed_at timestamptz,
  result jsonb not null default '{}'::jsonb
);

create index if not exists idx_app_feedback_status on public.app_feedback (status, created_at);

alter table public.app_feedback enable row level security;

revoke all on public.app_feedback from anon, authenticated;
grant insert (kind, question, answer_excerpt, correction, source_url, cited_facts, app_version)
  on public.app_feedback to anon;

drop policy if exists app_feedback_insert_only on public.app_feedback;
create policy app_feedback_insert_only on public.app_feedback
  for insert to anon
  with check (status = 'new' and processed_at is null and result = '{}'::jsonb);
